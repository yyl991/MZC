-- ============================================================
-- AO3 玩家留言表 · 幂等合并脚本（可重复执行，一次 Run 完）
-- 用途：存放「来源调查里选了 ao3 的玩家」发给恩仔的全部留言
-- 数据来源：
--   source_survey     → 找出 source='ao3' 的玩家 uid
--   replies_numbered  → 这些玩家的第几条回复(nth)、时间、留言正文
--   replies           → 补 ip / region（视图里没有这两列，按 id 关联）
-- 用法：Supabase 控制台 → SQL Editor → 粘贴全部 → Run
-- 项目：oprecriimhoisvvwazte（与 replies / source_survey 同一个项目）
-- 注意：本脚本是快照表——每次 Run 会清空 ao3_messages 再重灌，
--       只动 ao3_messages 自己，不修改 replies / source_survey 的任何数据和结构。
-- ============================================================

-- 1) 建表（幂等）
create table if not exists ao3_messages (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  uid text,         -- 玩家设备ID（两张源表都没有昵称，用 uid 作为玩家标识）
  nth bigint,       -- 该玩家的第几条回复（来自 replies_numbered.nth）
  time text,        -- 留言时间（视图 reply_time）
  text text,        -- 留言内容（视图 reply_text）
  ip text,          -- 留言 IP（来自 replies.ip）
  region text,      -- 留言地区（来自 replies.region）
  source text default 'ao3'  -- 来源标记，固定 ao3
);
-- 兼容此前已建过的旧表（旧表没有 nth 列）
alter table ao3_messages add column if not exists nth bigint;

-- 2) 依赖视图：与原「回复收集合并脚本」里的定义完全一致，create or replace 幂等。
--    若你已跑过那段脚本、视图已存在，这步只是重建同定义，无任何影响。
create or replace view replies_numbered as
select
row_number() over (partition by uid order by id) as nth,
id,
uid,
"time"   as reply_time,
"text"   as reply_text
from replies;

-- 3) 行级安全 + 匿名读取策略（幂等）
alter table ao3_messages enable row level security;
drop policy if exists "anyone can read ao3_messages" on ao3_messages;
create policy "anyone can read ao3_messages"
  on ao3_messages for select to public
  using (true);

-- 4) 抽取快照（幂等：先清空再重灌，重跑不会产生重复行）
delete from ao3_messages;

insert into ao3_messages (uid, nth, time, text, ip, region, source)
select
  rn.uid,
  rn.nth,
  rn.reply_time,
  rn.reply_text,
  r.ip,
  r.region,
  'ao3'
from replies_numbered rn
join replies r on r.id = rn.id
where exists (
  select 1 from source_survey s
  where s.uid = rn.uid and s.source = 'ao3'
);

