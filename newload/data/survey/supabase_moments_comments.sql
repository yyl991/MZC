-- ============================================================
-- 朋友圈评论收集 · 完整合并脚本（客户端代码不用改）
-- 可重复执行，全部幂等，一次 Run 完
-- 背景：客户端 collectMomentReply 一直在往 moments 表上报，但此前没建表，
--       404 被静默吞掉；建表后评论即可自动上报成功。
-- 上报字段：time / ip / region / uid / post / content
--   post 格式 = "朋友圈主人｜朋友圈正文前60字"（分隔符全角 ｜ U+FF5C）
--     → 这就是「评论的是哪条朋友圈」的标识
-- nth：该用户（uid）的第几条朋友圈评论，与 replies.nth 同款机制
--   （客户端不上报 nth，由 trigger 在插入时自动填 + 视图现算）
-- 项目：oprecriimhoisvvwazte（与 replies / source_survey 同一个项目）
-- 注意：只新建 moments 表 + 视图 + 触发器，不修改 replies / source_survey 的任何数据。
-- ============================================================

-- 0) 先删旧视图再重建（按依赖逆序）
--    原因：CREATE OR REPLACE VIEW 只能追加末尾列，不能改已有列的顺序/名字；
--    之前旧版 detail 第一列是 time、现在变成 nth，直接 replace 会报 42P16。
--    删视图不影响底层表和数据；drop 不带 cascade，若有其它对象依赖会安全报错。
drop view if exists moments_comment_summary;
drop view if exists moments_comment_detail;
drop view if exists moments_numbered;

-- 1) 建表（幂等）
create table if not exists moments (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  nth bigint,       -- 该用户的第几条朋友圈评论（由 trigger 自动填）
  time text,        -- 玩家设备本地时间字符串
  ip text,
  region text,
  uid text,         -- 设备ID
  post text,        -- 哪条朋友圈：朋友圈主人｜正文前60字
  content text      -- 评论内容
);
-- 兼容此前已建过的旧表（旧表没有 nth 列）
alter table moments add column if not exists nth bigint;

-- 2) 行级安全 + 允许匿名插入（与 replies / source_survey 同款策略）
alter table moments enable row level security;
drop policy if exists "anyone can insert moments" on moments;
create policy "anyone can insert moments"
  on moments for insert to public
  with check (true);

-- 3) 查看视图：第几条用 row_number() 现算，永远正确、不受 RLS 影响
--    （与 replies_numbered 完全同款）
create or replace view moments_numbered as
select
  row_number() over (partition by uid order by id) as nth,
  id,
  uid,
  "time"   as reply_time,
  post,
  content  as reply_text
from moments;

-- 4) 触发器：security definer 绕过 RLS，新评论插入时自动填原表 nth
--    （与 set_reply_nth 完全同款）
create or replace function set_moment_nth()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  select count(*) + 1 into new.nth from moments where uid = new.uid;
  return new;
end;
$$;
drop trigger if exists trg_set_moment_nth on moments;
create trigger trg_set_moment_nth
before insert on moments
for each row execute function set_moment_nth();

-- 5) 回填历史 nth（与回复脚本同款）
with ranked as (
  select id, row_number() over (partition by uid order by id) as rn
  from moments
)
update moments m set nth = ranked.rn
from ranked where m.id = ranked.id;

-- 6) 明细视图：每条评论 + nth + 拆出「哪条朋友圈」
create or replace view moments_comment_detail as
select
  nth,                                  -- 该用户的第几条朋友圈评论
  time,
  uid,                                  -- 评论者设备ID
  ip,
  region,
  split_part(post, '｜', 1) as moment_owner,   -- 朋友圈主人（chatId）
  split_part(post, '｜', 2) as moment_text,    -- 被评论的那条朋友圈正文（前60字）
  content as reply_text,                -- 评论内容
  post as post_raw                      -- 原始 post 字段（保留核对用）
from moments;

-- 7) 分类汇总视图：每条朋友圈多少条评论
create or replace view moments_comment_summary as
select
  moment_owner,
  moment_text,
  count(*) as comment_count,            -- 这条朋友圈收到的评论数
  count(distinct uid) as commenter_count, -- 多少个人评论过
  string_agg(distinct uid, '、' order by uid) as commenter_ids -- 回复者id列表（去重）
from moments_comment_detail
group by moment_owner, moment_text
order by comment_count desc;

