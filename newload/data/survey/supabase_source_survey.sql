-- ============================================================
-- 来源调查表（与恩仔聊天回复 replies 表完全独立）
-- 用途：存放「你是从哪里捡到这部手机」的玩家回答
-- 用法：Supabase 控制台 → SQL Editor → 粘贴全部内容 → Run
-- 项目：oprecriimhoisvvwazte（与现有 replies / visits / moments 同一个 Supabase 项目）
-- ============================================================

create table if not exists source_survey (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  time text,        -- 玩家设备本地时间字符串
  uid text,         -- 设备ID（D 开头，可关联 visits / replies 判断谁答过）
  ip text,
  region text,
  source text,      -- 选的来源：微博/小红书/抖音/ao3/朋友分享/其他
  detail text       -- 选「其他」时填的补充文本，没填为空串
);

alter table source_survey enable row level security;

-- 允许匿名玩家插入（与 replies 表同款策略；publishable key 需同时带 apikey + Authorization 头）
create policy "anyone can insert source_survey"
  on source_survey for insert to public
  with check (true);
