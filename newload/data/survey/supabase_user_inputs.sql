-- ============================================================
-- 玩家自主输入内容 · 5 张新表（可重复执行，全部幂等，一次 Run 完）
-- 用途：收集玩家在游戏里主动打字填写的内容，补齐此前未回收的 5 处
--   1) user_wx_chat      微信聊天（玩家发给各角色的消息）
--   2) user_moment_posts 朋友圈发帖（玩家发的文字动态）
--   3) user_sms          短信（玩家发出的短信）
--   4) user_notes        备忘录（玩家新建/编辑的备忘）
--   5) user_mails        邮件（玩家写出的邮件）
-- 共同字段：time / uid / ip / region —— 每张表都有 uid（设备ID），满足"所有数据带用户ID"
--   uid 与现有 replies / visits / source_survey / moments 的 uid 同源（window.getDeviceId），
--   可用 uid 把同一玩家在全部表里的行为串起来。
-- 项目：oprecriimhoisvvwazte（与 replies / visits / moments / source_survey 同一个 Supabase 项目）
-- 用法：Supabase 控制台 → SQL Editor → 粘贴全部 → Run
-- 安全：只新建这 5 张表 + 各自的 RLS/插入策略，不修改、不删除任何现有表和现有数据。
-- 前端：客户端会在发送/保存时静默上报；建表后数据自动进来，未建表期间上报被静默忽略（本机不受影响）。
-- ============================================================

-- ---------- 1) 微信聊天消息 ----------
create table if not exists user_wx_chat (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  time text,        -- 玩家设备本地时间字符串
  uid text,         -- 设备ID（所有表统一带 uid）
  ip text,
  region text,
  chat text,        -- 和谁聊天（如 恩仔/丞哥/pig/cat/rabbit/tiger/MuAMuA…）
  text text         -- 发出的消息正文
);
alter table user_wx_chat enable row level security;
drop policy if exists "anyone can insert user_wx_chat" on user_wx_chat;
create policy "anyone can insert user_wx_chat"
  on user_wx_chat for insert to public with check (true);

-- ---------- 2) 朋友圈发帖 ----------
create table if not exists user_moment_posts (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  time text,
  uid text,
  ip text,
  region text,
  text text,        -- 发帖文字（配图本身不上传，只记图片张数）
  image_count int default 0  -- 附带图片数量
);
alter table user_moment_posts enable row level security;
drop policy if exists "anyone can insert user_moment_posts" on user_moment_posts;
create policy "anyone can insert user_moment_posts"
  on user_moment_posts for insert to public with check (true);

-- ---------- 3) 短信 ----------
create table if not exists user_sms (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  time text,
  uid text,
  ip text,
  region text,
  to_who text,      -- 发送对象（会话标识/联系人）
  text text         -- 短信正文
);
alter table user_sms enable row level security;
drop policy if exists "anyone can insert user_sms" on user_sms;
create policy "anyone can insert user_sms"
  on user_sms for insert to public with check (true);

-- ---------- 4) 备忘录 ----------
create table if not exists user_notes (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  time text,
  uid text,
  ip text,
  region text,
  title text,       -- 备忘录标题
  body text         -- 备忘录正文
);
alter table user_notes enable row level security;
drop policy if exists "anyone can insert user_notes" on user_notes;
create policy "anyone can insert user_notes"
  on user_notes for insert to public with check (true);

-- ---------- 5) 邮件 ----------
create table if not exists user_mails (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  time text,
  uid text,
  ip text,
  region text,
  to_who text,      -- 收件人
  subject text,     -- 主题
  body text         -- 正文
);
alter table user_mails enable row level security;
drop policy if exists "anyone can insert user_mails" on user_mails;
create policy "anyone can insert user_mails"
  on user_mails for insert to public with check (true);

